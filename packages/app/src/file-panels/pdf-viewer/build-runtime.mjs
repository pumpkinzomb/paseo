import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const root = path.dirname(fileURLToPath(import.meta.url));
const distribution = path.dirname(require.resolve("pdfjs-dist/package.json"));
const assets = {};
for (const directory of ["cmaps", "standard_fonts", "wasm"]) {
  for (const name of (await fs.readdir(path.join(distribution, directory))).sort()) {
    if (!/\.(bcmap|pfb|ttf|otf|wasm)$/.test(name) || name.startsWith("quickjs")) continue;
    assets[`${directory}/${name}`] = (
      await fs.readFile(path.join(distribution, directory, name))
    ).toString("base64");
  }
}
const worker = await fs.readFile(path.join(distribution, "build/pdf.worker.min.mjs"), "utf8");
const result = await esbuild.build({
  entryPoints: [path.join(root, "runtime/entry.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "chrome120",
  minify: true,
  define: { __PDF_WORKER__: JSON.stringify(worker), __PDF_ASSETS__: JSON.stringify(assets) },
  logLevel: "warning",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const styles = await fs.readFile(path.join(root, "runtime/style.css"), "utf8");
const libraryStyles = await fs.readFile(path.join(distribution, "web/pdf_viewer.css"), "utf8");
// Only text-layer rules are needed. The distribution's full stylesheet includes unrelated viewer controls/assets.
const start = libraryStyles.search(/\.textLayer\s*\{/);
const end = libraryStyles.indexOf(".annotationLayer", start);
if (start < 0 || end < 0) throw Error("PDF.js text-layer stylesheet changed; review required");
const textStyles = libraryStyles.slice(start, end);
if (/url\(/i.test(textStyles)) throw Error("Unexpected external PDF text-layer asset");
const licenses = [];
for (const directory of ["", "cmaps", "standard_fonts", "wasm"]) {
  const entries = await fs.readdir(path.join(distribution, directory), { withFileTypes: true });
  for (const entry of entries.toSorted((a, b) => a.name.localeCompare(b.name, "en"))) {
    if (entry.isFile() && entry.name.startsWith("LICENSE"))
      licenses.push(
        `${directory}/${entry.name}\n${await fs.readFile(path.join(distribution, directory, entry.name), "utf8")}`,
      );
  }
}
const licenseText = licenses
  .join("\n\n")
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;");
const version = JSON.parse(await fs.readFile(path.join(distribution, "package.json"))).version;
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval' blob:; worker-src blob:; style-src 'unsafe-inline'; img-src data: blob:; font-src data: blob:; connect-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'"><style>${textStyles}\n${styles}</style></head><body><template id="pdf-third-party-licenses">${licenseText}</template><div id="pdf-root"></div><script>${js}</script></body></html>`;
await fs.writeFile(
  path.join(root, "runtime/html.gen.ts"),
  `// Generated by pdf-viewer/build-runtime.mjs. Do not edit by hand.\nexport const pdfRuntimeVersion = ${JSON.stringify(version)};\nexport const pdfRuntimeHtml = ${JSON.stringify(html)};\n`,
);
console.log(
  `Bundled PDF.js ${JSON.parse(await fs.readFile(path.join(distribution, "package.json"))).version}, worker and ${Object.keys(assets).length} local resources (${html.length} bytes)`,
);

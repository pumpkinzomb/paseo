import fs from "node:fs/promises";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { atomicJson } from "./dev-update-store.mjs";
import { dependencyRootsIn, processesUsing } from "./stopped-build-dependencies.mjs";
const exec = promisify(execFile);
const git = async (root, args) =>
  (await exec("git", args, { cwd: root, maxBuffer: 16 * 1024 ** 2 })).stdout;

// For a newly-created, initially clean build sandbox owned by this invocation.
// Never used to guess ownership of a legacy lab or ordinary developer checkout.
export async function reclaimOwnedBuildOutputs(
  { root, identity, sourceRevision },
  { active = processesUsing } = {},
) {
  async function owned() {
    const info = await fs.lstat(root);
    if (
      (await fs.realpath(root)) !== root ||
      !info.isDirectory() ||
      info.isSymbolicLink() ||
      info.dev !== identity.dev ||
      info.ino !== identity.ino ||
      info.uid !== process.getuid() ||
      info.mode & 0o077
    )
      throw new Error("Build scratch ownership changed");
    const meta = await fs.lstat(path.join(root, ".git"));
    if (
      !meta.isDirectory() ||
      meta.isSymbolicLink() ||
      (await git(root, ["rev-parse", "HEAD"])).trim() !== sourceRevision
    )
      throw new Error("Build scratch revision changed");
  }
  await owned();
  if (await active(root)) return { state: "retained", reason: "process-using-build" };
  const candidates = await dependencyRootsIn(root);
  // These are the outputs generated by this staging pipeline, not user-selected
  // paths. A tracked file anywhere underneath excludes the whole output root.
  for (const name of [
    "app",
    "server",
    "client",
    "protocol",
    "desktop",
    "cli",
    "plugin",
    "highlight",
    "relay",
  ]) {
    const relative = `packages/${name}/dist`;
    try {
      const info = await fs.lstat(path.join(root, relative));
      if (info.isDirectory() && !info.isSymbolicLink()) candidates.push(relative);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  const removed = [],
    retained = [];
  for (const relative of candidates) {
    const absolute = path.join(root, relative);
    if (
      (await fs.realpath(absolute)) !== absolute ||
      (await git(root, ["--literal-pathspecs", "ls-files", "-z", "--", relative])).length
    ) {
      retained.push(relative);
      continue;
    }
    await owned();
    if (await active(root))
      return { state: "partial", reason: "process-using-build", removed, retained };
    const stat = await fs.lstat(absolute);
    if (!stat.isDirectory() || stat.isSymbolicLink()) {
      retained.push(relative);
      continue;
    }
    await fs.rm(absolute, { recursive: true });
    removed.push(relative);
  }
  const result = {
    state: "outputs-reclaimed",
    sourceRevision,
    removed,
    retained,
    restore: "npm ci, then the recorded build commands",
  };
  await atomicJson(path.join(root, "rebuild-outputs.json"), result);
  return result;
}
